/**
 * Turn a measurement run into `lib/model-context.js`.
 *
 * The gateway's `/v1/models` carries no context window at all, so the plugin
 * has to know these numbers itself. They are measured, not guessed: a prompt
 * larger than the model's window is rejected before generation with a message
 * naming the limit (or, for models that do not name it, the boundary is found
 * by bisection between a known-good and a known-bad size).
 *
 * Usage: node scripts/build-context-table.mjs /tmp/ctx_bisect.json
 */

import { readFile, writeFile } from "node:fs/promises";

const SOURCES = process.argv.slice(2);
if (SOURCES.length === 0) SOURCES.push("/tmp/ctx_bisect.json", "/tmp/ctx_retry.json");
const OUT = new URL("../lib/model-context.js", import.meta.url);

/** Merge every measurement run; a later run wins for the same model. */
const raw = {};
for (const source of SOURCES) {
  let parsed;
  try {
    parsed = JSON.parse(await readFile(source, "utf8"));
  } catch {
    continue; // a run that never started leaves no file
  }
  for (const [id, record] of Object.entries(parsed)) {
    if (Number(record?.context) > 0) raw[id] = { ...raw[id], ...record };
  }
}

/** @type {Array<{id: string, contextWindow: number, maxTokens: number|undefined}>} */
const rows = [];
for (const [id, record] of Object.entries(raw)) {
  const contextWindow = Number(record?.context);
  if (!Number.isFinite(contextWindow) || contextWindow <= 0) continue;
  rows.push({ id, contextWindow, maxTokens: Number(record?.maxTokens) || undefined });
}
rows.sort((a, b) => a.id.localeCompare(b.id));

const entries = rows
  .map((row) => {
    const parts = [`contextWindow: ${row.contextWindow}`];
    if (row.maxTokens !== undefined) parts.push(`maxTokens: ${row.maxTokens}`);
    return `  ${JSON.stringify(row.id)}: { ${parts.join(", ")} },`;
  })
  .join("\n");

const file = `/**
 * Context windows measured against the gateway, one entry per model id.
 *
 * Generated by \`scripts/build-context-table.mjs\` from a measurement run — do
 * not edit by hand. \`/v1/models\` from sub2api returns only ids, so without this
 * table every model would fall back to the default window, which is what made
 * a 200k-context model advertise 128k in the picker.
 *
 * Measured ${new Date().toISOString().slice(0, 10)} against ${process.env.SUB2API_PROBE_BASE ?? "the configured gateway"}.
 * ${rows.length} models.
 *
 * @type {Record<string, {contextWindow: number, maxTokens?: number}>}
 */
export const MEASURED_CONTEXT = {
${entries}
};

/**
 * Known facts for \`id\`, preferring the longest matching id.
 *
 * The gateway lists both \`deepseek-v4-pro\` and \`deepseek/deepseek-v4-pro\`; an
 * exact hit wins, then the longest id that the requested one extends.
 * @param {string} id
 * @returns {{contextWindow: number, maxTokens?: number} | undefined}
 */
export function measuredContext(id) {
  const key = String(id ?? "").trim();
  if (key === "") return undefined;
  const exact = MEASURED_CONTEXT[key];
  if (exact !== undefined) return exact;

  const lower = key.toLowerCase();
  let best;
  for (const [known, facts] of Object.entries(MEASURED_CONTEXT)) {
    const name = known.toLowerCase();
    if (!lower.startsWith(name)) continue;
    if (best === undefined || name.length > best.length) best = { length: name.length, facts };
  }
  return best?.facts;
}
`;

await writeFile(OUT, file, "utf8");
console.log(`wrote ${rows.length} entries to lib/model-context.js`);
